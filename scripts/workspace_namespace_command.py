"""Explicit prepare/apply entry for a reviewed canonical namespace cutover.

Installed infrastructure and product drivers are immutable store paths. The
private input is generated by the product layout planner, never downloaded or
accepted from an HTTP request. No action is performed on import.
"""
import argparse
from dataclasses import replace
import importlib
import json
import re
from pathlib import Path
import sys

from application_entry_transaction import private,digest
from native_application_release import Manager,fixed_scope as application_scope
from workspace_namespace_transaction import Cutover,fixed_scope

DRIVER_FILES=('workspace_namespace_release.py','workspace_namespace_plan.py','workspace_namespace_store.py','workspace_namespace_references.py','workspace_namespace_identities.py','workspace_namespace_layout.py','workspace_namespace_journals.py')


def driver(directory):
    directory=Path(directory)
    if not re.fullmatch(r'/nix/store/[a-z0-9]{32}-[^/]+/libexec',str(directory)) or not directory.is_dir() or directory.resolve()!=directory:
        raise ValueError('Frozen installed product driver directory required')
    hashes={}
    for name in DRIVER_FILES:
        path=directory/name
        if not path.is_file() or not path.resolve().is_relative_to(directory.resolve()):
            raise ValueError('Product driver is incomplete')
        hashes[str(path)]=digest(path)
    sys.path.insert(0,str(directory))
    product=importlib.import_module('workspace_namespace_release')
    for name in DRIVER_FILES:
        module=sys.modules.get(name.removesuffix('.py'))
        if module is not None and Path(module.__file__).resolve()!=directory/name:
            raise ValueError('A different product driver is already loaded')
    return product,hashes


def controller(name,product):
    scope=fixed_scope(name);base=application_scope(name)
    # NUC read-only services and their state are outside this migration.
    manager=Manager(replace(base,units=scope.units,states=(scope.state,),connections=base.connections[:1],probes=base.probes[:1]))
    apply,status=product.ports(scope.state/'core.db')
    return Cutover(scope,manager,apply,status)


def verify_inputs(plan):
    for path,sha in plan['input_sha256'].items():
        source=Path(path)
        if not re.fullmatch(r'/nix/store/[a-z0-9]{32}-[^/]+(?:/.*)?',str(source)) or source.resolve()!=source or digest(source)!=sha:
            raise ValueError('Frozen namespace input changed')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--scope',choices=['pc','nuc'],required=True)
    parser.add_argument('--driver',type=Path,required=True)
    sub=parser.add_subparsers(dest='action',required=True)
    prepare=sub.add_parser('prepare');prepare.add_argument('--request',type=Path,required=True)
    for name in ['apply','cancel-before-commit']:
        command=sub.add_parser(name);command.add_argument('--release',type=Path,required=True)
        command.add_argument('--editors-saved',action='store_true')
    args=parser.parse_args();product,hashes=driver(args.driver)
    for name in ['workspace_namespace_command.py','workspace_namespace_transaction.py','native_application_release.py','application_entry_transaction.py']:
        path=Path(__file__).parent/name;hashes[str(path)]=digest(path)
    cutover=controller(args.scope,product)
    if args.action=='prepare':
        value=json.loads(private(args.request).read_text())
        if set(value)!={'files','roots','product_request','input_sha256','product_preview_sha256'}:
            raise ValueError('Reviewed product layout request required')
        plan={'schema':1,'scope':args.scope,'namespace':str(cutover.scope.namespace),
              'state_policy':'never-restore-database','files':value['files'],'roots':value['roots'],
              'product':product.prepare(cutover.scope.state/'core.db',value['product_request']),
              'input_sha256':{**value['input_sha256'],**hashes},'upholding':cutover.manager.uphold_binding()}
        if plan['product']['database']['manifest_sha256']!=value['product_preview_sha256']:
            raise ValueError('Database changed after rendering the reviewed layout; prepare again')
        local=plan['product']['request']['namespace_paths']
        if local!={('loc_pc' if args.scope=='pc' else 'default'):str(cutover.scope.namespace)}:
            raise ValueError('Product and infrastructure namespace scope differ')
        verify_inputs(plan)
        release=cutover.prepare(plan)
        print(json.dumps({'phase':'prepared','release':str(release),'production_database_written':False}))
    else:
        _,plan=cutover.load(args.release)
        if not all(plan['input_sha256'].get(path)==sha for path,sha in hashes.items()):
            raise ValueError('Use the same frozen infrastructure and product drivers for recovery')
        verify_inputs(plan)
        method=cutover.apply if args.action=='apply' else cutover.cancel_before_commit
        print(json.dumps(method(args.release,editors_saved=args.editors_saved)))


if __name__=='__main__':main()
